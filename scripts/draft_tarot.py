# Which themes a card's direction applies to; the knowledge review rubric quotes this too.
MAJOR_THEMES = ["self", "career", "relationship"]
SUIT_THEMES = {
    "wands": ["career", "self"],
    "cups": ["relationship", "self"],
    "swords": ["self", "career"],
    "pentacles": ["finance", "career"],
}


def draft(output: Path) -> None:
    if output.exists():
        raise FileExistsError("源文件已存在；请直接审核编辑，脚本不覆盖人工修改")
    entries = []
    for i, (card_id, name) in enumerate(DECK):
        if i < 22:
            words, upright, reversed_text, up_value, reversed_value = MAJOR_DRAFTS[i]
            themes = MAJOR_THEMES
        else:
            suit = card_id.split("_")[0]
            words, upright, reversed_text, up_value, reversed_value = MINOR_DRAFTS[suit][
                (i - 22) % 14
            ]
            themes = SUIT_THEMES[suit]
        for orientation, text, value in [
            ("upright", upright, up_value),
            ("reversed", reversed_text, reversed_value),
        ]:
            key = f"{card_id}:{orientation}"
            entries.append(
                {
                    "id": f"kb:tarot:card:{key}",
                    "system": "tarot",
                    "kind": "card",
                    "key": key,
                    "synonyms": [f"{name}:{'正位' if orientation == 'upright' else '逆位'}"],
                    "keywords": words.split(","),
                    "theme_map": {theme: value for theme in themes},
                    "text": text + "这是象征性反思线索，不代表事件必然发生。",
                    "source": "本项目自写象征释义草稿；未引用现代网站或书籍文案",
                    "license": "本项目自写",
                    "reviewed": False,
                    "version": 1,
                }
            )
    for spread, positions in SPREADS.items():
        for i, label in enumerate(positions, 1):
            key = f"{spread}:{i}"
            entries.append(
                {
                    "id": f"kb:tarot:position:{key}",
                    "system": "tarot",
                    "kind": "position",
                    "key": key,
                    "synonyms": [],
                    "keywords": [label],
                    "theme_map": {},
                    "text": f"此牌位用于梳理“{label}”的象征线索。未来牌位表达反思方向，不作确定性预测。",
                    "source": "本项目自写牌位说明",
                    "license": "本项目自写",
                    "reviewed": False,
                    "version": 1,
                }
            )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        yaml.safe_dump(
            {"schema_version": 1, "entries": entries},
            allow_unicode=True,
            sort_keys=False,
            width=100,
        ),
        encoding="utf-8",
    )


if __name__ == "__main__":
    draft(Path(__file__).resolve().parents[1] / "knowledge/sources/tarot/cards.yaml")
